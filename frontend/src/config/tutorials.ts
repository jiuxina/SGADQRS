const FALLBACK = (pageName: string): Tutorial => T(`${pageName} · 使用帮助`, [
  ['关于本页', `当前页面为「${pageName}」。`],
  ['通用提示', '悬浮左侧栏可展开查看各页面入口；右上角铃铛查看通知；遇到问题请联系管理员。'],
])

export function resolveTutorial(pathname: string, tab: string | null, fallbackName: string): Tutorial {
  if (tab) {
    const hit = TUTORIALS[`${pathname}|${tab}`]
    if (hit) return hit
  }
  const exact = TUTORIALS[pathname]
  if (exact) return exact
  for (const [re, t] of REGEX_TUTORIALS) {
    if (re.test(pathname)) return t
  }
  return FALLBACK(fallbackName || '本页')
}
